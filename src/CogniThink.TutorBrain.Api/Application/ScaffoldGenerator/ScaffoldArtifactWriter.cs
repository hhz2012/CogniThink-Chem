namespace CogniThink.TutorBrain.Application.ScaffoldGenerator;

using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;

// ============================================================
// Task 5: 生成产物落盘为前端可消费的 .ts（默认产物格式，spec Open Question）。
// 幂等铁律（TR-5.2）：同输入 → 字节级一致。
//   - STJ 属性按声明序输出（稳定）；Dictionary 按插入序（稳定，同插入序列）；
//   - 枚举走 JsonStringEnumConverter（稳定字面量）；
//   - JavaScriptEncoder 不转义中文（稳定且可读）；
//   - 发布前按 id 排序（调用方保证），此处只负责序列化。
// 不旁路写文件：这是生成器唯一产物出口（主链路），前端只从此处读取。
// ============================================================

public static class ScaffoldArtifactWriter
{
    // 注意：不在 options 注册 JsonStringEnumConverter——它会优先于类型上的 [JsonConverter] 特性，
    // 且不识别 [EnumMember]/[JsonPropertyName]。枚举名由 ScaffoldGeneratorContracts 上的
    // [JsonConverter(typeof(EnumMemberJsonConverter<T>))] 统一处理（输出前端连字符字面量）。
    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    /// <summary>把脚手架列表序列化为前端可 import 的 .ts 文本。</summary>
    public static string ToTs(IReadOnlyList<GeneratedScaffold> scaffolds)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// AUTO-GENERATED by ScaffoldGenerator. Do not edit by hand.");
        sb.AppendLine("// 相对路径基于最终落盘位置 miniapp/src/data/scaffolds/generated/index.ts");
        sb.AppendLine("import type { GeneratedScaffold } from '../../../types/scaffold';");
        sb.AppendLine();
        sb.AppendLine("export const GENERATED_SCAFFOLDS: GeneratedScaffold[] = [");
        for (int i = 0; i < scaffolds.Count; i++)
        {
            var json = JsonSerializer.Serialize(scaffolds[i], JsonOpts);
            var indented = "  " + json.Replace("\n", "\n  ");
            sb.Append(indented);
            if (i < scaffolds.Count - 1) sb.Append(',');
            sb.AppendLine();
        }
        sb.AppendLine("];");
        // 统一行尾为 \n：与 OS 无关，保证跨平台字节幂等（AppendLine 在 Windows 下为 \r\n）。
        return sb.ToString().Replace("\r\n", "\n").Replace("\r", "");
    }

    /// <summary>幂等写盘：目录不存在则创建；同输入同内容 → 覆盖后字节一致。</summary>
    public static void WriteTs(string path, IReadOnlyList<GeneratedScaffold> scaffolds)
    {
        var dir = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(path, ToTs(scaffolds), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    }
}
