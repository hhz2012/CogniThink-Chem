namespace CogniThink.Chem.Core.Molecules;

/// <summary>
/// 高中课内官能团词表（单一真相源）：名称 → SMARTS。
/// 由 <see cref="MoleculeAnalyzer"/>（特征提取/判分）与 <see cref="MoleculeValidator"/>（白名单校验）
/// 共用，从根源杜绝两套词表口径漂移。
/// SMARTS 设计原则：只识别不预测；用负向环境排除交叉误报
/// （羧基中的羟基、酯中的醚键、酰胺/硝基中的氨基均不重复计）。
/// </summary>
public static class FunctionalGroupVocabulary
{
    public static readonly (string Name, string Smarts)[] InScope =
    {
        ("苯环", "c1ccccc1"),
        ("碳碳双键", "C=C"),
        ("碳碳三键", "C#C"),
        ("羟基", "[OX2H;!$([OX2H][CX3]=O)]"),
        ("羧基", "[CX3](=O)[OX2H]"),
        ("醛基", "[$([CX3H1](=O)[#6]),$([CX3H2]=O)]"),
        ("酮羰基", "[CX3](=O)([#6])[#6]"),
        // 羰基：酮羰基的答案口径别名（答案写「羰基」而未写「酮羰基」时命中）；仅酮羰基触发，不泛化到醛/羧/酯
        ("羰基", "[CX3](=O)([#6])[#6]"),
        ("酯基", "[CX3](=O)[OX2][#6]"),
        // 醚键：允许两侧为 sp³/sp²/芳基碳；负向排除酯的烷氧基氧；[#6] 不含 H → 自动排除醇/酚/羧基 O–H
        ("醚键", "[OD2;!$([OD2][CX3]=O)]([#6])[#6]"),
        // 氨基：覆盖伯/仲/叔胺；负向排除酰胺 N（连羰基碳）与硝基 N（连氧）
        ("氨基", "[NX3;!$([NX3][CX3]=O);!$([NX3]~O)][#6]"),
        // 酰胺基 / 肽键：同一酰胺结构，发两个名以覆盖两种答案口径
        ("酰胺基", "[CX3](=O)[NX3]"),
        ("肽键", "[CX3](=O)[NX3]"),
        // 硫醚：二价硫且两邻位均为碳 → 自动排除硫醇([SX2H])、二硫(S–S)、亚砜/砜(高次价)
        ("硫醚", "[SX2]([#6])[#6]"),
        ("硝基", "[$([NX3](=O)=O),$([NX3+](=O)[O-])]"),
        ("卤原子", "[F,Cl,Br,I][#6]"),
        // 卤素具体名：答案口径别名（「溴原子/碳溴键」等）。保留「卤原子」以兼容旧口径
        ("溴原子", "[Br][#6]"),
        ("碳溴键", "[Br][#6]"),
        ("氯原子", "[Cl][#6]"),
        ("碳氯键", "[Cl][#6]"),
        ("氟原子", "[F][#6]"),
        ("碳氟键", "[F][#6]"),
        ("碘原子", "[I][#6]"),
        ("碳碘键", "[I][#6]"),
    };
}
